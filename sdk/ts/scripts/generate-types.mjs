// Generates sdk/ts/src/generated/* from schemas/*.schema.json (the contract's single source of truth is the
// Pydantic models in core/; schemas/ is generated from them). Never edit the output by hand.
import { readFileSync, readdirSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemasDir = resolve(here, "../../../schemas");
const outDir = resolve(here, "../src/generated");
const banner = "/* GENERATED by sdk/ts/scripts/generate-types.mjs from schemas/. Do not edit by hand. */";

const index = JSON.parse(readFileSync(join(schemasDir, "index.json"), "utf8"));
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const exports = [];
for (const file of readdirSync(schemasDir).filter((f) => f.endsWith(".schema.json")).sort()) {
  const name = file.replace(".schema.json", "");
  // JsonValue is "any JSON value": without this json-schema-to-typescript types `{}` plus a default as an object.
  const anyJson = (node) => {
    if (Array.isArray(node)) return node.map(anyJson);
    if (node && typeof node === "object") {
      if (typeof node.$ref === "string" && node.$ref.endsWith("/JsonValue")) return { tsType: "unknown" };
      return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, anyJson(v)]));
    }
    return node;
  };
  const schema = anyJson(JSON.parse(readFileSync(join(schemasDir, file), "utf8")));
  const ts = await compile(schema, schema.title ?? name, {
    bannerComment: banner,
    additionalProperties: false,
    unknownAny: true,
    format: false,
    declareExternallyReferenced: true,
    strictIndexSignatures: false,
  });
  writeFileSync(join(outDir, `${name}.ts`), ts);
  if (schema.title) exports.push(`export type { ${schema.title} } from "./${name}";`);
}
writeFileSync(
  join(outDir, "index.ts"),
  `${banner}\nexport const CONTRACT_VERSION = ${JSON.stringify(index.contract_version)};\n${exports.join("\n")}\n`,
);
console.log(`generated ${exports.length} schema modules (contract ${index.contract_version})`);
